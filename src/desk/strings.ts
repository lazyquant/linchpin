/** Sentences with a public word in them. No argument is ever a value of the book. */
export const DESK_TEXT = Object.freeze({
  addressItem: (ordinal: number, chain: string): string => `address ${ordinal}, chain ${chain}`,
  chainItem: (chain: string): string => `chain ${chain}`,
  ruleItem: (ruleId: string): string => `rule ${ruleId}`,
  notRead: (reason: string): string => `not read: ${reason}`,
  readerError: (code: string): string => `reader error: ${code}`,
  positionsListed: (count: number): string => (count === 1 ? "1 position listed" : `${count} positions listed`),
  positionsOnRoot: (count: number): string => (count === 1 ? "1 position" : `${count} positions`),
  summary: (positions: number, root: string, outside: number): string =>
    `${positions === 1 ? "1 position" : `${positions} positions`} on ${root}: ${outside === 1 ? "1 rule outside policy names" : `${outside} rules outside policy name`} this chain`,
  summaryUncovered: (positions: number, root: string): string =>
    `${positions === 1 ? "1 position" : `${positions} positions`} on ${root}: this subject is not in the snapshot`,
  explainQuestion: (ruleId: string, subjects: string[]): string => `Explain rule ${ruleId} on ${subjects.join(", ")}.`,
  changesTitle: (before: string): string => `Changes since ${before}`,
  policyTitle: (policyId: string): string => `Policy ${policyId}`,
  morePositions: (count: number): string => (count === 1 ? "1 more NEAR position is not drawn" : `${count} more NEAR positions are not drawn`),
});
